import test from 'node:test';
import assert from 'node:assert/strict';
import http from 'node:http';
import net from 'node:net';
import { once, EventEmitter } from 'node:events';
import { WebSocket } from 'ws';
import mqtt from 'mqtt';
import { Aedes } from 'aedes';
import { createRealtime } from '../src/websocket/websocketServer.js';
import { createMqtt } from '../src/mqtt/mqttClient.js';

test('WebSocket filters devices, rejects bad origins and sends no initial fake snapshot', async (t) => {
    const server = http.createServer();
    const realtime = createRealtime(server, { allowedOrigins: ['http://localhost:5173'] });
    await new Promise((r) => server.listen(0, '127.0.0.1', r));
    const url = `ws://127.0.0.1:${server.address().port}/ws`;
    const client = new WebSocket(`${url}?device_code=PM-ESP32-001`, { origin: 'http://localhost:5173' });
    t.after(async () => { client.terminate(); await realtime.close(); await new Promise((r) => server.close(r)); });
    await once(client, 'open');
    const received = [];
    client.on('message', (data) => received.push(JSON.parse(data)));
    realtime.broadcast('measurement', { device_code: 'PM-ESP32-002', voltage: 120 });
    const message = once(client, 'message');
    realtime.broadcast('measurement', { device_code: 'PM-ESP32-001', voltage: 220 });
    await message;
    assert.equal(received.length, 1);
    assert.equal(received[0].data.voltage, 220);
    const bad = new WebSocket(url, { origin: 'https://evil.example' });
    await assert.rejects(once(bad, 'open'), /403/);
});

test('MQTT subscribes, survives malformed payload and reconnects', async (t) => {
    const broker = await Aedes.createBroker();
    const tcp = net.createServer(broker.handle);
    await new Promise((r) => tcp.listen(0, '127.0.0.1', r));
    const url = `mqtt://127.0.0.1:${tcp.address().port}`;
    const accepted = [];
    const config = { mqttUrl: url, mqttClientId: 'backend-test', maxPayloadBytes: 4096, maxPendingMessages: 10 };
    const signals = new EventEmitter();
    const connection = createMqtt({ config, services: { acceptMessage: async (message) => { accepted.push(message); signals.emit('accepted'); }, event: async () => {} }, logger: { error() {}, info() {} } });
    const device = mqtt.connect(url);
    t.after(async () => { await connection.close(); await device.endAsync(true); await new Promise((r) => tcp.close(r)); await broker.close(); });
    await once(device, 'connect');
    await connection.ready;
    await device.publishAsync('powermeter/PM-ESP32-001/measurement', '{', { qos: 1 });
    const payload = { device_code: 'PM-ESP32-001', voltage: 220, current: 1, active_power: 220, energy_wh: 1, recorded_at: new Date().toISOString() };
    const stored = once(signals, 'accepted');
    await device.publishAsync('powermeter/PM-ESP32-001/measurement', JSON.stringify(payload), { qos: 1 });
    await stored;
    await connection.idle();
    assert.equal(accepted.length, 1);
    const reconnect = once(connection.client, 'connect');
    const subscribed = once(connection.client, 'packetsend');
    connection.client.reconnect();
    await reconnect;
    await subscribed;
    await new Promise((r) => connection.client.subscribe('test/ready', r));
    const heartbeat = once(signals, 'accepted');
    await device.publishAsync('powermeter/PM-ESP32-001/heartbeat', JSON.stringify({ device_code: 'PM-ESP32-001' }), { qos: 1 });
    await heartbeat;
    await connection.idle();
    assert.ok(accepted.some((m) => m.type === 'heartbeat'));
});
