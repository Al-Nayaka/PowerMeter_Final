import test from 'node:test';
import assert from 'node:assert/strict';
import net from 'node:net';
import { once } from 'node:events';
import { Aedes } from 'aedes';
import mqtt from 'mqtt';
import { WebSocket } from 'ws';
import { testDatabase } from './helpers/database.js';
import { createRuntime } from '../src/runtime.js';

test('full local pipeline MQTT -> SQL commit -> WebSocket -> REST, then relay ACK and graceful shutdown', { timeout: 20000 }, async (t) => {
    const { pool } = await testDatabase();
    const broker = await Aedes.createBroker();
    const tcp = net.createServer(broker.handle);
    await new Promise((r) => tcp.listen(0, '127.0.0.1', r));
    const mqttUrl = `mqtt://127.0.0.1:${tcp.address().port}`;
    const config = { port: 0, host: '127.0.0.1', mqttUrl, mqttClientId: 'integration-backend', maxPayloadBytes: 4096, maxPendingMessages: 100, allowedOrigins: ['http://localhost:5173'], adminKey: 'integration-key', historyMaxLimit: 1000, offlineTimeoutMs: 45000, relayTimeoutMs: 10000 };
    const runtime = await createRuntime({ config, pool, logger: { error() {}, info() {} } });
    const device = mqtt.connect(mqttUrl);
    const deviceReady = once(device, 'connect');
    let ws;
    t.after(async () => { ws?.terminate(); await device.endAsync(true); await runtime.close(); await new Promise((r) => tcp.close(r)); await broker.close(); });
    await runtime.start();
    await runtime.mqtt.ready;
    await deviceReady;
    const base = `http://127.0.0.1:${runtime.server.address().port}`;
    const code = 'PM-ESP32-001';
    const headers = { Authorization: 'Bearer integration-key', 'Content-Type': 'application/json' };
    assert.equal((await fetch(`${base}/api/health`)).status, 200);
    assert.equal((await fetch(`${base}/api/devices`, { method: 'POST', headers, body: JSON.stringify({ device_code: code, device_name: 'Panel Test', mqtt_topic_prefix: `powermeter/${code}` }) })).status, 201);
    ws = new WebSocket(`${base.replace('http:', 'ws:')}/ws?device_code=${code}`);
    await once(ws, 'open');
    const measurement = new Promise((resolve) => ws.on('message', (raw) => { const message = JSON.parse(raw); if (message.type === 'measurement') resolve(message.data); }));
    const data = { device_code: code, message_id: 'integration-1', voltage: 220, current: 1, active_power: 220, energy_wh: 123, power_factor: null, recorded_at: new Date().toISOString() };
    await device.publishAsync(`powermeter/${code}/measurement`, JSON.stringify(data), { qos: 1 });
    const stored = await measurement;
    assert.ok(stored.id);
    const latest = await (await fetch(`${base}/api/measurements/latest/${code}`)).json();
    assert.equal(String(latest.data.id), String(stored.id));
    const history = await (await fetch(`${base}/api/measurements/history/${code}?limit=1`)).json();
    assert.equal(history.data.length, 1);
    await device.subscribeAsync(`powermeter/${code}/relay/command`, { qos: 1 });
    device.on('message', async (topic, raw) => {
        const cmd = JSON.parse(raw);
        await device.publishAsync(`powermeter/${code}/relay/state`, JSON.stringify({ ...cmd, confirmed_at: new Date().toISOString() }), { qos: 1 });
    });
    const relayState = new Promise((resolve) => ws.on('message', (raw) => { const message = JSON.parse(raw); if (message.type === 'relay_state') resolve(message.data); }));
    const response = await fetch(`${base}/api/relays/${code}/commands`, { method: 'POST', headers, body: JSON.stringify({ relay_number: 1, state: true }) });
    assert.equal(response.status, 202);
    const confirmed = await relayState;
    assert.equal(confirmed.state, true);
    const command = await (await fetch(`${base}/api/relays/${code}/commands/${confirmed.command_id}`, { headers })).json();
    assert.equal(command.data.status, 'confirmed');
});
